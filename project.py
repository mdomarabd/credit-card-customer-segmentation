def interpret_clusters(profile, method_name):
    print(f"\n\n=== INTERPRETATION FOR {method_name} ===")
    for c in profile.index:
        print(f"\nCluster {c}:")
        desc = profile.loc[c]
        high = desc[desc > desc.mean()].index.tolist()
        low  = desc[desc < desc.mean()].index.tolist()
        print(f" • High values: {', '.join(high) if high else 'None'}")
        print(f" • Low values: {', '.join(low) if low else 'None'}")

